"""Kiểm tra cấu hình TRƯỚC KHI chạy thật trên máy chủ (không in giá trị bí mật nào).

    python scripts/preflight.py            # in báo cáo
    python scripts/preflight.py --strict   # thoát mã 1 nếu còn mục CHƯA ĐẠT (dùng trong systemd)
"""
from __future__ import annotations

import argparse
import os
import stat
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.config import settings  # noqa: E402
from app.core.security import verify_password  # noqa: E402

DEMO_PASSWORDS = {  # tài khoản mẫu do app/db/seed.py tạo
    "NV001": "employee123", "NV002": "employee123", "TT001": "officer123",
    "GD001": "director123", "AD001": "admin123",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args()
    results: list[tuple[bool, str, str]] = []

    def check(ok: bool, name: str, fix: str = "") -> None:
        results.append((ok, name, fix))

    check(not settings.jwt_secret_autogenerated,
          "JWT_SECRET_KEY riêng, đủ mạnh trong backend/.env",
          'Đặt JWT_SECRET_KEY=<python -c "import secrets; print(secrets.token_urlsafe(48))">')
    check(not settings.SHOW_DEMO_ACCOUNTS, "Ẩn tài khoản dùng thử ở trang đăng nhập", "SHOW_DEMO_ACCOUNTS=false")
    check(not settings.ENABLE_API_DOCS, "Tắt tài liệu API /docs", "ENABLE_API_DOCS=false")
    check("*" not in settings.cors_origin_list, "CORS không để '*'", "CORS_ORIGINS=https://api.ten-mien-cua-ban.vn")
    check(not settings.DATABASE_URL.startswith("sqlite") or "app.db" in settings.DATABASE_URL,
          "Cơ sở dữ liệu cấu hình rõ ràng")

    keys = Path(settings.KEYS_DIR)
    if keys.is_dir():
        mode = stat.S_IMODE(keys.stat().st_mode)
        check(mode & 0o077 == 0, "Thư mục khóa chỉ chủ sở hữu truy cập được (chmod 700)", f"chmod 700 {keys}")
    else:
        check(False, "Thư mục khóa tồn tại", "Khởi động app một lần để sinh khóa")

    try:
        from app.db.session import SessionLocal
        from app.models.identified import User
        with SessionLocal() as db:
            weak = [u.employee_code for u in db.query(User).filter(User.employee_code.in_(DEMO_PASSWORDS)).all()
                    if u.is_active and verify_password(DEMO_PASSWORDS[u.employee_code], u.password_hash)]
        check(not weak, "Không còn tài khoản mẫu dùng mật khẩu mặc định",
              f"Đổi mật khẩu hoặc khóa: {', '.join(weak)} (scripts/manage_roles.py reset-password / lock)" if weak else "")
    except Exception as exc:  # CSDL chưa khởi tạo
        check(False, "Đọc được cơ sở dữ liệu", type(exc).__name__)

    log_file = os.getenv("LOG_FILE", str(Path(__file__).resolve().parents[1] / "logs" / "app.log"))
    if log_file:
        parent = Path(log_file).parent
        check(parent.exists() and os.access(parent, os.W_OK) or not parent.exists(),
              "Ghi được file log", f"Cấp quyền ghi cho {parent}")

    failed = 0
    for ok, name, fix in results:
        print(f"[{'ĐẠT' if ok else 'CHƯA ĐẠT'}] {name}" + ("" if ok or not fix else f"\n           -> {fix}"))
        failed += not ok
    print(f"\n{len(results) - failed}/{len(results)} mục đạt.")
    return 1 if (args.strict and failed) else 0


if __name__ == "__main__":
    raise SystemExit(main())
